-- Автопапка «Наталы» (по аналогии с «Хорары»/«Электив»/«Синастрии»).
-- Колонка folder уже существует (см. supabase_horary.sql) — здесь только
-- разовая раскладка ранее сохранённых наталов, включая старые строки,
-- записанные до появления case_type.
-- Приложение делает то же самое на клиенте при загрузке списка карт
-- (backfillNatalFolder), так что запуск этого файла необязателен.

update public.charts
   set folder = 'Наталы'
 where folder is null
   and (case_type is null or case_type = 'natal');
